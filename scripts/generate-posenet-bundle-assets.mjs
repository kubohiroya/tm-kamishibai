import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const repositoryRoot = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const sourceDirectory = path.join(repositoryRoot, 'assets/posenet/mobilenet-v1-075-stride16');
const outputPath = path.join(repositoryRoot, 'src/dsl4/platform/posenet-bundle-assets.js');
const files = [
  ['model-stride16.json', 'application/json'],
  ['group1-shard1of2.bin', 'application/octet-stream'],
  ['group1-shard2of2.bin', 'application/octet-stream'],
];

function sourceLiteral(value) {
  return JSON.stringify(value);
}

const entries = [];
for (const [name, mediaType] of files) {
  const bytes = await readFile(path.join(sourceDirectory, name));
  entries.push(
    `  Object.freeze({path: ${sourceLiteral(name)}, mediaType: ${sourceLiteral(mediaType)}, base64: ${sourceLiteral(bytes.toString('base64'))}})`,
  );
}

const source = `/* This file is generated by scripts/generate-posenet-bundle-assets.mjs. */
/** @param {string} value */
function decodeBase64(value) {
  if (typeof atob !== 'function') throw new Error('K4-POSENET-ASSET-001: atob is required');
  const decoded = atob(value);
  const bytes = new Uint8Array(decoded.length);
  for (let index = 0; index < decoded.length; index += 1) bytes[index] = decoded.charCodeAt(index);
  return bytes;
}

export const embeddedPoseNetFiles = Object.freeze([
${entries.join(',\n')},
].map(({path, mediaType, base64}) =>
  Object.freeze({path, mediaType, bytes: decodeBase64(base64)}),
));
`;

await writeFile(outputPath, source);
