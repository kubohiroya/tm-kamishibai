import {readFile, mkdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createDsl4BlockAuthoringExtensionSource} from '../dist/dsl4/structured-block-source.js';
import {dsl4RuntimeBlockIconURI} from '../dist/dsl4/runtime-icon.js';
const root = fileURLToPath(new URL('../', import.meta.url));
/** Emit a fixed owner artifact; runtime bundles must not inline registration-source generators. */
export async function generateEmbeddedYamlAuthoringRuntime() {
  const metadata = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
  const author = metadata.author;
  const header = [
    '// Name: Kamishibai DSL 4.0 Authoring',
    '// ID: kubohiroyakamishibaiauthoring4',
    '// Description: Inert owner schema declarations for embedded YAML source views.',
    '// Description[ja]: 組込YAMLのスキーマ専用ブロックを表示する、実行しない宣言用拡張です。',
    `// By: ${author.name}`,
    `// Author URL: ${author.url}`,
    `// Version: ${metadata.version}`,
    `// Repository: ${metadata.repository.url.replace(/^git\+/u, '').replace(/\.git$/u, '')}`,
    `// Docs URL: ${metadata.homepage}`,
    `// Banner: ${dsl4RuntimeBlockIconURI}`,
    `// Package: ${metadata.name}`,
    '// License: MPL-2.0',
    '// Unsandboxed: required',
    '',
  ].join('\n');
  const source =
    header +
    createDsl4BlockAuthoringExtensionSource([], {
      narrativeControlEnabled: true,
      referenceViews: true,
    });
  const url = 'data:text/javascript;base64,' + Buffer.from(source).toString('base64');
  const module =
    '// Generated by scripts/generate-embedded-yaml-authoring-runtime.mjs.\n/** @type {string} */\nexport const embeddedYamlAuthoringRuntimeURL = ' +
    JSON.stringify(url) +
    ';\n';
  for (const prefix of ['src', 'dist']) {
    const file = path.join(root, prefix, 'dsl4/generated/embedded-yaml-authoring-runtime.js');
    await mkdir(path.dirname(file), {recursive: true});
    await writeFile(file, module);
  }
  return url;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await generateEmbeddedYamlAuthoringRuntime();
